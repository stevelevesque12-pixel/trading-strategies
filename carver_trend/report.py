"""Run the standard variants and write carver_trend/RESULTS.md + equity.png."""
import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

import backtest as bt

HERE = Path(__file__).resolve().parent
BASE = dict(end="2100-01-01", capital=1_000_000, emac_filters=6, cap=20, sigma_span=32,
            target_risk=0.2, blend_years=3, buffer_scaler=0.1, regime=True, fractional=False,
            instruments=None)
VARIANTS = [
    ("Adjusted trend (regime), 2000-2024", dict(start="2000-01-01")),
    ("Plain multi-trend (no regime), 2000-2024", dict(start="2000-01-01", regime=False)),
    ("Adjusted trend, QC 5y window 2019-03 to 2024-03", dict(start="2019-03-28")),
    ("Plain multi-trend, QC 5y window", dict(start="2019-03-28", regime=False)),
    ("Adjusted trend, fractional contracts, 2000-2024", dict(start="2000-01-01", fractional=True)),
]


def main():
    rows, curves, main_res = [], {}, None
    for name, kw in VARIANTS:
        p = argparse.Namespace(**{**BASE, **kw})
        res = bt.run(p)
        net = res["net"].sum(axis=1)
        s = bt.stats(net, p.capital)
        g = bt.stats(res["gross"].sum(axis=1), p.capital)
        rows.append({"variant": name, **{k: round(v, 2) for k, v in s.items()},
                     "gross_sharpe": round(g["sharpe"], 2),
                     "cost_%/yr": round(100 * res["cost"].sum().sum() / p.capital / (len(net) / bt.DAYS), 2)})
        if kw.get("start") == "2000-01-01" and not kw.get("fractional"):
            curves[name.split(",")[0]] = 100 * net.cumsum() / p.capital
        if main_res is None:
            main_res = res

    table = pd.DataFrame(rows).set_index("variant")
    net, meta = main_res["net"], main_res["meta"]
    by_inst = pd.DataFrame({
        "name": meta["name"], "class": meta["asset_class"],
        "net_pnl_$k": (net.sum() / 1e3).round(0),
        "sharpe": (net.mean() / net.std() * 16).round(2),
        "avg_|contracts|": main_res["held"].abs().mean().round(2),
    }).sort_values("net_pnl_$k", ascending=False)
    by_class = (net.T.groupby(meta["asset_class"]).sum().T.sum() / 1e3).round(0).sort_values(ascending=False)
    yearly = (net.sum(axis=1).resample("YE").sum() / 1e4).round(1)
    yearly.index = yearly.index.year

    fig, ax = plt.subplots(figsize=(10, 4.8), dpi=130)
    for (label, c), color in zip(curves.items(), ["#2a78d6", "#eb6834"]):
        ax.plot(c.index, c.values, color=color, lw=2, label=label)
        ax.annotate(f"{c.iloc[-1]:.0f}%", (c.index[-1], c.iloc[-1]), xytext=(4, 0),
                    textcoords="offset points", va="center", fontsize=9, color="#52514e")
    ax.set_title("Cumulative net return, % of $1M fixed capital (38 US futures, daily)",
                 loc="left", fontsize=11, color="#0b0b0b")
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.grid(axis="y", color="#e5e4e0", lw=0.8)
    ax.tick_params(colors="#52514e", labelsize=9)
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    fig.tight_layout()
    fig.savefig(HERE / "equity.png")

    md = [
        "# Adjusted trend backtest: all major US futures\n",
        "Generated by `python carver_trend/report.py`. Method and assumptions are in `backtest.py`'s docstring and the README.\n",
        "## Summary\n", table.to_markdown(), "\n![equity](equity.png)\n",
        "## Net P&L by asset class, adjusted trend 2000-2024 ($k)\n", by_class.to_frame("net_pnl_$k").to_markdown(),
        "\n## Yearly net return, adjusted trend (% of capital)\n", yearly.to_frame("return_%").T.to_markdown(),
        "\n## Per instrument, adjusted trend 2000-2024\n", by_inst.to_markdown(),
    ]
    (HERE / "RESULTS.md").write_text("\n".join(md) + "\n")
    print(table.to_string())


if __name__ == "__main__":
    main()
